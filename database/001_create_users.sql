CREATE SEQUENCE SEQ_CSBET_USERS
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;

CREATE TABLE CSBET_USERS (
    ID NUMBER(19) NOT NULL,
    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    EMAIL VARCHAR2(150 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    BALANCE NUMBER(15,2) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CSBET_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_CSBET_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_CSBET_USERS_EMAIL UNIQUE (EMAIL)
);
