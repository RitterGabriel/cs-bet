CREATE SEQUENCE CSBET.SEQ_CSBET_INVENTORY START WITH 1 INCREMENT BY 1 NOCYCLE;

-- Cada linha representa uma unidade; OWNER_ID + SKIN_ID não é uma chave única.
CREATE TABLE CSBET.CSBET_INVENTORY_ITEMS (
    ID NUMBER(19) NOT NULL,
    OWNER_ID NUMBER(19) NOT NULL,
    SKIN_ID NUMBER(19) NOT NULL,
    OBTAINED_AT TIMESTAMP(6) NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
    SOLD_AT TIMESTAMP(6),
    SALE_PRICE NUMBER(18,2),
    CONSTRAINT PK_CSBET_INVENTORY PRIMARY KEY (ID),
    CONSTRAINT FK_CSBET_INV_OWNER FOREIGN KEY (OWNER_ID) REFERENCES CSBET.CSBET_USERS(ID),
    CONSTRAINT FK_CSBET_INV_SKIN FOREIGN KEY (SKIN_ID) REFERENCES CSBET.CSBET_COSMETIC_ITEMS(ID),
    CONSTRAINT CK_CSBET_INV_STATUS CHECK (STATUS IN ('AVAILABLE', 'SOLD')),
    CONSTRAINT CK_CSBET_INV_SALE CHECK (
        (STATUS = 'AVAILABLE' AND SOLD_AT IS NULL AND SALE_PRICE IS NULL)
        OR (STATUS = 'SOLD' AND SOLD_AT IS NOT NULL AND SALE_PRICE IS NOT NULL
            AND SALE_PRICE >= 0 AND SOLD_AT >= OBTAINED_AT)
    )
);
CREATE INDEX CSBET.IX_CSBET_INV_OWNER_STATUS ON CSBET.CSBET_INVENTORY_ITEMS(OWNER_ID, STATUS, OBTAINED_AT, ID);
CREATE INDEX CSBET.IX_CSBET_INV_OWNER_DATE ON CSBET.CSBET_INVENTORY_ITEMS(OWNER_ID, OBTAINED_AT, ID);
CREATE INDEX CSBET.IX_CSBET_INV_SKIN ON CSBET.CSBET_INVENTORY_ITEMS(SKIN_ID);
