CREATE SEQUENCE SEQ_CSBET_WALLET_MOVEMENTS START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE CSBET_WALLET_MOVEMENTS (
    ID NUMBER(19) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    TYPE VARCHAR2(20 CHAR) NOT NULL,
    AMOUNT NUMBER(18,2) NOT NULL,
    RESULTING_BALANCE NUMBER(18,2) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    REQUEST_ID VARCHAR2(36 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_WALLET_MOVEMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_WALLET_USER FOREIGN KEY (USER_ID) REFERENCES CSBET_USERS(ID),
    CONSTRAINT UK_WALLET_REQUEST UNIQUE (USER_ID, REQUEST_ID),
    CONSTRAINT CK_WALLET_TYPE CHECK (TYPE = 'CREDIT_ADDITION'),
    CONSTRAINT CK_WALLET_AMOUNT CHECK (AMOUNT > 0 AND AMOUNT <= 10000),
    CONSTRAINT CK_WALLET_BALANCE CHECK (RESULTING_BALANCE >= 0)
);
CREATE INDEX IX_WALLET_USER_DATE ON CSBET_WALLET_MOVEMENTS (USER_ID, CREATED_AT DESC, ID DESC);
