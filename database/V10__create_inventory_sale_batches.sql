-- Recibo idempotente da venda de todas as unidades cotadas, exclusivamente fictícias.
CREATE SEQUENCE SEQ_CSBET_SALE_BATCHES START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE CSBET_SALE_BATCHES (
    ID NUMBER(19) NOT NULL PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL REFERENCES CSBET_USERS(ID),
    REQUEST_ID VARCHAR2(36 CHAR) NOT NULL,
    FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL CHECK (QUANTITY > 0),
    AMOUNT NUMBER(18,2) NOT NULL CHECK (AMOUNT > 0),
    RESULTING_BALANCE NUMBER(18,2) NOT NULL CHECK (RESULTING_BALANCE >= 0),
    CREATED_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT UK_SALE_BATCH_REQUEST UNIQUE (USER_ID, REQUEST_ID)
);
