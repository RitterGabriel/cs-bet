-- Regras próprias do CS Bet, separadas das probabilidades das caixas oficiais.
CREATE TABLE CSBET_CUSTOM_CASES (
    CASE_ID NUMBER(19) NOT NULL PRIMARY KEY REFERENCES CSBET_CASES(ID),
    CREDIT_PRICE NUMBER(18,2) NOT NULL CHECK (CREDIT_PRICE > 0),
    ACCENT VARCHAR2(7 CHAR) NOT NULL,
    RULE_VERSION VARCHAR2(40 CHAR) NOT NULL,
    FINGERPRINT VARCHAR2(64 CHAR) NOT NULL
);
CREATE SEQUENCE SEQ_CSBET_CUSTOM_ENTRIES START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE CSBET_CUSTOM_ENTRIES (
    ID NUMBER(19) NOT NULL PRIMARY KEY,
    CASE_ID NUMBER(19) NOT NULL REFERENCES CSBET_CUSTOM_CASES(CASE_ID),
    SKIN_ID NUMBER(19) NOT NULL REFERENCES CSBET_COSMETIC_ITEMS(ID),
    WEIGHT NUMBER(5) NOT NULL CHECK (WEIGHT > 0 AND WEIGHT <= 10000),
    CONSTRAINT UK_CUSTOM_CASE_SKIN UNIQUE (CASE_ID, SKIN_ID)
);
CREATE TABLE CSBET_CUSTOM_VARIANTS (
    ENTRY_ID NUMBER(19) NOT NULL REFERENCES CSBET_CUSTOM_ENTRIES(ID),
    VARIANT_ID NUMBER(19) NOT NULL REFERENCES CSBET_MARKET_VARIANTS(ID),
    CONSTRAINT PK_CUSTOM_VARIANTS PRIMARY KEY (ENTRY_ID, VARIANT_ID)
);
CREATE INDEX IX_CUSTOM_VARIANT ON CSBET_CUSTOM_VARIANTS(VARIANT_ID);
CREATE INDEX IX_CUSTOM_ENTRY_SKIN ON CSBET_CUSTOM_ENTRIES(SKIN_ID);
