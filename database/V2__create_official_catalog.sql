-- Executado pelo Flyway apenas no comando explícito --catalog-import.
-- Baseline 1 corresponde à CSBET_USERS existente; esta migração não a altera.
CREATE SEQUENCE CSBET.SEQ_CSBET_CASES START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE CSBET.SEQ_CSBET_COSMETIC_ITEMS START WITH 1 INCREMENT BY 1 NOCYCLE;

CREATE TABLE CSBET.CSBET_RARITIES (
    ID VARCHAR2(80 CHAR) NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    COLOR VARCHAR2(7 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_RARITIES PRIMARY KEY (ID),
    CONSTRAINT CK_CSBET_RARITIES_COLOR CHECK (REGEXP_LIKE(COLOR, '^#[0-9a-fA-F]{6}$'))
);
CREATE TABLE CSBET.CSBET_CASES (
    ID NUMBER(19) NOT NULL,
    SOURCE VARCHAR2(40 CHAR) NOT NULL,
    EXTERNAL_ID VARCHAR2(120 CHAR) NOT NULL,
    NAME VARCHAR2(250 CHAR) NOT NULL,
    CATEGORY VARCHAR2(20 CHAR) NOT NULL,
    CONTAINER_TYPE VARCHAR2(40 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(4000 CHAR),
    IMAGE_URL VARCHAR2(2048 CHAR),
    SOURCE_REVISION VARCHAR2(40 CHAR) NOT NULL,
    SOURCE_LANGUAGE VARCHAR2(10 CHAR) NOT NULL,
    IMPORTED_AT TIMESTAMP(6) NOT NULL,
    SPECIAL_NOTICE VARCHAR2(1000 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_CASES PRIMARY KEY (ID),
    CONSTRAINT UK_CSBET_CASES_SOURCE UNIQUE (SOURCE, EXTERNAL_ID),
    CONSTRAINT CK_CSBET_CASES_CATEGORY CHECK (CATEGORY IN ('official', 'custom'))
);
CREATE TABLE CSBET.CSBET_COSMETIC_ITEMS (
    ID NUMBER(19) NOT NULL,
    SOURCE VARCHAR2(40 CHAR) NOT NULL,
    EXTERNAL_ID VARCHAR2(120 CHAR) NOT NULL,
    NAME VARCHAR2(250 CHAR) NOT NULL,
    WEAPON VARCHAR2(120 CHAR) NOT NULL,
    WEAPON_TYPE VARCHAR2(120 CHAR) NOT NULL,
    SPECIAL_CATEGORY VARCHAR2(20 CHAR) NOT NULL,
    IMAGE_URL VARCHAR2(2048 CHAR),
    RARITY_ID VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_COSMETIC_ITEMS PRIMARY KEY (ID),
    CONSTRAINT UK_CSBET_ITEMS_SOURCE UNIQUE (SOURCE, EXTERNAL_ID),
    CONSTRAINT FK_CSBET_ITEMS_RARITY FOREIGN KEY (RARITY_ID) REFERENCES CSBET.CSBET_RARITIES(ID),
    CONSTRAINT CK_CSBET_ITEMS_SPECIAL CHECK (SPECIAL_CATEGORY IN ('none', 'knife', 'glove'))
);
CREATE TABLE CSBET.CSBET_CASE_ITEMS (
    CASE_ID NUMBER(19) NOT NULL,
    ITEM_ID NUMBER(19) NOT NULL,
    SPECIAL VARCHAR2(1 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_CASE_ITEMS PRIMARY KEY (CASE_ID, ITEM_ID),
    CONSTRAINT FK_CSBET_LINK_CASE FOREIGN KEY (CASE_ID) REFERENCES CSBET.CSBET_CASES(ID),
    CONSTRAINT FK_CSBET_LINK_ITEM FOREIGN KEY (ITEM_ID) REFERENCES CSBET.CSBET_COSMETIC_ITEMS(ID),
    CONSTRAINT CK_CSBET_LINK_SPECIAL CHECK (SPECIAL IN ('Y', 'N'))
);
CREATE INDEX CSBET.IX_CSBET_CASES_CATEGORY_NAME ON CSBET.CSBET_CASES(CATEGORY, NAME);
CREATE INDEX CSBET.IX_CSBET_CASES_NAME_LOWER ON CSBET.CSBET_CASES(LOWER(NAME));
CREATE INDEX CSBET.IX_CSBET_ITEMS_RARITY ON CSBET.CSBET_COSMETIC_ITEMS(RARITY_ID);
CREATE INDEX CSBET.IX_CSBET_LINK_ITEM ON CSBET.CSBET_CASE_ITEMS(ITEM_ID);
