-- V4 permanece intacta como histórico de simulação. Não converte seus valores para BRL.
CREATE SEQUENCE CSBET.SEQ_CSBET_MARKET_VARIANTS START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE SEQUENCE CSBET.SEQ_CSBET_MARKET_HISTORY START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE CSBET.CSBET_MARKET_VARIANTS (
    ID NUMBER(19) NOT NULL,
    SKIN_ID NUMBER(19),
    CASE_ID NUMBER(19),
    MARKET_HASH_NAME VARCHAR2(300 CHAR) NOT NULL,
    WEAR VARCHAR2(8 CHAR) NOT NULL,
    STAT_TRAK VARCHAR2(1 CHAR) NOT NULL,
    SOUVENIR VARCHAR2(1 CHAR) NOT NULL,
    PRICE_AMOUNT NUMBER(18,2) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    QUOTE_SOURCE VARCHAR2(40 CHAR) NOT NULL,
    PROVIDER VARCHAR2(100 CHAR) NOT NULL,
    QUOTED_AT TIMESTAMP(6) NOT NULL,
    FETCHED_AT TIMESTAMP(6) NOT NULL,
    VALID_UNTIL TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CSBET_MARKET_VARIANTS PRIMARY KEY (ID),
    CONSTRAINT FK_CSBET_MARKET_SKIN FOREIGN KEY (SKIN_ID) REFERENCES CSBET.CSBET_COSMETIC_ITEMS(ID),
    CONSTRAINT FK_CSBET_MARKET_CASE FOREIGN KEY (CASE_ID) REFERENCES CSBET.CSBET_CASES(ID),
    CONSTRAINT UK_CSBET_MARKET_HASH UNIQUE (MARKET_HASH_NAME),
    CONSTRAINT UK_CSBET_MARKET_SKIN UNIQUE (SKIN_ID, WEAR, STAT_TRAK, SOUVENIR),
    CONSTRAINT UK_CSBET_MARKET_CASE UNIQUE (CASE_ID),
    CONSTRAINT UK_CSBET_MARKET_ID_SKIN UNIQUE (ID, SKIN_ID),
    CONSTRAINT CK_CSBET_MARKET_TARGET CHECK ((SKIN_ID IS NOT NULL AND CASE_ID IS NULL) OR (CASE_ID IS NOT NULL AND SKIN_ID IS NULL)),
    CONSTRAINT CK_CSBET_MARKET_WEAR CHECK (WEAR IN ('NONE', 'FN', 'MW', 'FT', 'WW', 'BS')),
    CONSTRAINT CK_CSBET_MARKET_FLAGS CHECK (STAT_TRAK IN ('Y', 'N') AND SOUVENIR IN ('Y', 'N') AND NOT (STAT_TRAK = 'Y' AND SOUVENIR = 'Y')),
    CONSTRAINT CK_CSBET_MARKET_CASE_KIND CHECK (CASE_ID IS NULL OR (WEAR = 'NONE' AND STAT_TRAK = 'N' AND SOUVENIR = 'N')),
    CONSTRAINT CK_CSBET_MARKET_AMOUNT CHECK (PRICE_AMOUNT > 0 AND CURRENCY = 'BRL'),
    CONSTRAINT CK_CSBET_MARKET_SOURCE CHECK (QUOTE_SOURCE = 'STEAM_COMMUNITY_MARKET'),
    CONSTRAINT CK_CSBET_MARKET_DATES CHECK (VALID_UNTIL > QUOTED_AT AND FETCHED_AT >= QUOTED_AT)
);
CREATE TABLE CSBET.CSBET_MARKET_HISTORY (
    ID NUMBER(19) NOT NULL,
    VARIANT_ID NUMBER(19) NOT NULL,
    PRICE_AMOUNT NUMBER(18,2) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    QUOTE_SOURCE VARCHAR2(40 CHAR) NOT NULL,
    PROVIDER VARCHAR2(100 CHAR) NOT NULL,
    QUOTED_AT TIMESTAMP(6) NOT NULL,
    FETCHED_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_CSBET_MARKET_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_CSBET_MARKET_HIST FOREIGN KEY (VARIANT_ID) REFERENCES CSBET.CSBET_MARKET_VARIANTS(ID),
    CONSTRAINT UK_CSBET_MARKET_OBSERVATION UNIQUE (VARIANT_ID, QUOTED_AT),
    CONSTRAINT CK_CSBET_MARKET_HIST_AMOUNT CHECK (PRICE_AMOUNT > 0 AND CURRENCY = 'BRL'),
    CONSTRAINT CK_CSBET_MARKET_HIST_SOURCE CHECK (QUOTE_SOURCE = 'STEAM_COMMUNITY_MARKET')
);
CREATE TABLE CSBET.CSBET_MARKET_CONTROL (
    ID NUMBER(19) NOT NULL,
    LAST_ATTEMPT_AT TIMESTAMP(6),
    NEXT_ATTEMPT_AT TIMESTAMP(6),
    LAST_SUCCESS_AT TIMESTAMP(6),
    LAST_STATUS VARCHAR2(24 CHAR),
    CONSTRAINT PK_CSBET_MARKET_CONTROL PRIMARY KEY (ID),
    CONSTRAINT CK_CSBET_MARKET_CONTROL CHECK (ID = 1)
);
