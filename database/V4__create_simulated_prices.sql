CREATE SEQUENCE CSBET.SEQ_CSBET_PRICE_HISTORY START WITH 1 INCREMENT BY 1 NOCYCLE;
CREATE TABLE CSBET.CSBET_SIMULATED_PRICES (
    SKIN_ID NUMBER(19) NOT NULL,
    BASE_PRICE NUMBER(18,2) NOT NULL,
    CURRENT_PRICE NUMBER(18,2) NOT NULL,
    PRICE_DATE DATE NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    RULE_VERSION VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_SIMULATED_PRICES PRIMARY KEY (SKIN_ID),
    CONSTRAINT FK_CSBET_PRICE_SKIN FOREIGN KEY (SKIN_ID) REFERENCES CSBET.CSBET_COSMETIC_ITEMS(ID),
    CONSTRAINT CK_CSBET_PRICE_POSITIVE CHECK (BASE_PRICE > 0 AND CURRENT_PRICE > 0),
    CONSTRAINT CK_CSBET_PRICE_BOUNDS CHECK (CURRENT_PRICE >= BASE_PRICE * 0.5 AND CURRENT_PRICE <= BASE_PRICE * 1.5),
    CONSTRAINT CK_CSBET_PRICE_DAY CHECK (PRICE_DATE = TRUNC(PRICE_DATE))
);
CREATE TABLE CSBET.CSBET_PRICE_HISTORY (
    ID NUMBER(19) NOT NULL,
    SKIN_ID NUMBER(19) NOT NULL,
    PRICE_DATE DATE NOT NULL,
    AMOUNT NUMBER(18,2) NOT NULL,
    RECORDED_AT TIMESTAMP(6) NOT NULL,
    EVENT_TYPE VARCHAR2(16 CHAR) NOT NULL,
    CONSTRAINT PK_CSBET_PRICE_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_CSBET_HISTORY_SKIN FOREIGN KEY (SKIN_ID) REFERENCES CSBET.CSBET_COSMETIC_ITEMS(ID),
    CONSTRAINT UK_CSBET_HISTORY_DAY UNIQUE (SKIN_ID, PRICE_DATE),
    CONSTRAINT CK_CSBET_HISTORY_POSITIVE CHECK (AMOUNT > 0),
    CONSTRAINT CK_CSBET_HISTORY_EVENT CHECK (EVENT_TYPE IN ('INITIAL', 'DAILY')),
    CONSTRAINT CK_CSBET_HISTORY_DAY CHECK (PRICE_DATE = TRUNC(PRICE_DATE))
);
-- Linha sentinela bloqueada com PESSIMISTIC_WRITE durante toda a atualização.
