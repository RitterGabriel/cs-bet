    CONSTRAINT PK_CSBET_PRICE_CONTROL PRIMARY KEY (ID),
    CONSTRAINT CK_CSBET_PRICE_CONTROL_ID CHECK (ID = 1),
    CONSTRAINT CK_CSBET_CONTROL_DAY CHECK (LAST_RUN_DATE = TRUNC(LAST_RUN_DATE))
);
