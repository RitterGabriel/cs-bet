-- No Oracle, a chave composta parcialmente nula da V5 também restringia caixas
-- (SKIN_ID nulo, mas WEAR/flags iguais). A unicidade de variantes vale apenas para skins;
-- as caixas continuam protegidas pela UK_CSBET_MARKET_CASE existente.
ALTER TABLE CSBET.CSBET_MARKET_VARIANTS DROP CONSTRAINT UK_CSBET_MARKET_SKIN;
CREATE UNIQUE INDEX CSBET.UX_CSBET_MARKET_SKIN ON CSBET.CSBET_MARKET_VARIANTS (
    CASE WHEN SKIN_ID IS NOT NULL THEN SKIN_ID END,
    CASE WHEN SKIN_ID IS NOT NULL THEN WEAR END,
    CASE WHEN SKIN_ID IS NOT NULL THEN STAT_TRAK END,
    CASE WHEN SKIN_ID IS NOT NULL THEN SOUVENIR END
);
-- Preserva as referências/históricos Steam e os preços simulados V4.
ALTER TABLE CSBET.CSBET_MARKET_VARIANTS DROP CONSTRAINT CK_CSBET_MARKET_SOURCE;
ALTER TABLE CSBET.CSBET_MARKET_VARIANTS ADD CONSTRAINT CK_CSBET_MARKET_SOURCE
    CHECK (QUOTE_SOURCE IN ('STEAM_COMMUNITY_MARKET', 'MARKET_CSGO'));
ALTER TABLE CSBET.CSBET_MARKET_HISTORY DROP CONSTRAINT CK_CSBET_MARKET_HIST_SOURCE;
ALTER TABLE CSBET.CSBET_MARKET_HISTORY ADD CONSTRAINT CK_CSBET_MARKET_HIST_SOURCE
    CHECK (QUOTE_SOURCE IN ('STEAM_COMMUNITY_MARKET', 'MARKET_CSGO'));
ALTER TABLE CSBET.CSBET_MARKET_VARIANTS ADD (
    ORIGINAL_AMOUNT NUMBER(18,6), ORIGINAL_CURRENCY VARCHAR2(3 CHAR),
    EXCHANGE_RATE NUMBER(18,8), EXCHANGE_RATE_AT TIMESTAMP(6)
);
ALTER TABLE CSBET.CSBET_MARKET_HISTORY ADD (
    ORIGINAL_AMOUNT NUMBER(18,6), ORIGINAL_CURRENCY VARCHAR2(3 CHAR),
    EXCHANGE_RATE NUMBER(18,8), EXCHANGE_RATE_AT TIMESTAMP(6)
);
ALTER TABLE CSBET.CSBET_MARKET_VARIANTS ADD CONSTRAINT CK_CSBET_MARKET_FX CHECK (
    QUOTE_SOURCE <> 'MARKET_CSGO' OR (ORIGINAL_CURRENCY IS NOT NULL AND ORIGINAL_CURRENCY = 'USD'
    AND ORIGINAL_AMOUNT IS NOT NULL AND ORIGINAL_AMOUNT > 0 AND EXCHANGE_RATE IS NOT NULL
    AND EXCHANGE_RATE > 0 AND EXCHANGE_RATE_AT IS NOT NULL)
);
ALTER TABLE CSBET.CSBET_MARKET_HISTORY ADD CONSTRAINT CK_CSBET_MARKET_HIST_FX CHECK (
    QUOTE_SOURCE <> 'MARKET_CSGO' OR (ORIGINAL_CURRENCY IS NOT NULL AND ORIGINAL_CURRENCY = 'USD'
    AND ORIGINAL_AMOUNT IS NOT NULL AND ORIGINAL_AMOUNT > 0 AND EXCHANGE_RATE IS NOT NULL
    AND EXCHANGE_RATE > 0 AND EXCHANGE_RATE_AT IS NOT NULL)
);
